/* ===== #include 的底层原理 =====
 * 一个 .c 文件变成 .exe 要走四步：预处理(preprocess) → 编译(compile) → 汇编(assemble) → 链接(link)。
 * #include 发生在第一步"预处理"：预处理器把头文件的全部内容原样"复制粘贴"到这一行的位置。
 * 头文件里放的是函数的"声明"（告诉编译器函数叫什么名字、吃什么参数），
 * 函数真正的机器码在最后"链接"阶段才从 C 标准库（英文术语: libc）里合并进来。 */
#include <stdio.h>   // 包含标准输入输出库，提供printf等函数
#include <stdlib.h>  // 提供system函数
#include <string.h>  // 提供strlen函数
/* std==standard标准
i==input输入
o==output输出 */
int main(){
    /* system() 让操作系统替我们执行一条命令，就像自己在黑窗口里敲了一遍。
     * chcp 65001 把控制台「英文术语: codepage（代码页）」切换到 65001 号，
     * 65001 就是 UTF-8 编码的编号；不切的话，下面 printf 送出的 UTF-8 中文
     * 会被控制台按默认的 GBK 编码去解码 → 显示成乱码。 */
    system("chcp 65001");  // 设置终端编码为UTF-8，解决中文乱码

    /* 格式占位符的底层原理：内存里存的都是 0 和 1，二进制位本身没有"类型"。
     * 是格式符告诉 printf 按哪种规则去"解释"这些位——同一串位，%d 看成整数、%c 看成字符。
     * printf 的第 1 个参数叫「英文术语: format string（格式字符串）」，
     * 里面的 %d、%c 等占位符会被后面参数的值逐个替换；
     * printf 是 libc 提供的「行业术语: variadic function（可变参数函数）」，参数个数不固定。 */
    //%d:整数格式化输出
    //%f:浮点数格式化输出
    //%c:字符格式化输出
    //%s:字符串格式化输出
    //%p:指针格式化输出
    //%u:无符号整数格式化输出

    /* 转义字符在【编译期】就被替换成真实字节：\n→0x0A、\t→0x09、\\→一个反斜杠0x5C。
     * 运行时 printf 拿到的只是普通字节，不再做任何"翻译"。
     * 双引号括起来的字符串常量存放在「英文术语: .rodata（只读数据段）」，
     * 程序整个运行期间都躺在那里，只许读、不许改。 */
    printf("hello\tworld\n");
    printf("a\\b"); 

    // printf("100\n");      // 直接输出字符串"100"
    /* char 只占 1 字节（8 位），存的是一个整数编码——'A' 的编码是 65。
     * 「英文术语: ASCII（美国信息交换标准代码）」：给每个字符编一个整数编号的对照表。
     * 所以"字符的本质是整数"：同一个字节 65，%c 把它解释成字符 'A'，%d 把它解释成数字 65。 */
    char a = 'A';              // 定义字符变量a并初始化为'A'
    printf("%c\n",a);    // 使用%c格式化输出字符'A'
    printf("%d\n",a);    // 使用%d格式化输出字符'A'对应的ASCII码值（65）
    // printf("%f\n",100.0);  // 使用%f格式化输出浮点数100.0
    // printf("%c\n",'a');    // 使用%c格式化输出字符'a'
    // int a=15;                 // 定义整数变量a并初始化为15
    // scanf("%d",&a);        // 从键盘读取整数输入并存储到变量a中（%d=整数格式，&a=取变量a的地址）
    /* 为什么 scanf 要加 &？& 是「英文术语: address-of operator（取地址运算符）」，
     * 拿到变量 a 在「英文术语: stack（栈）」上的内存地址——栈是局部变量居住的内存区域，函数结束自动回收。
     * scanf 要把键盘输入【直接写进】a 的内存，必须知道"写到哪里"，所以要传地址；
     * printf 相反，它只是读取值的【副本】拿去显示，所以 printf 传值、scanf 传地址。 */
    // printf("%d\n",a);      // 输出读入的整数

    int i =0;              // 定义循环变量i并初始化为0
    /* 这个循环在"遍历 ASCII 表"：32 是空格，65~90 是 'A'~'Z'，97~122 是 'a'~'z'。
     * 注意 i 是 int（4 字节），传给 %c 时 printf 只取它的【最低 1 个字节】（低 8 位）当字符编码，
     * 高位直接丢掉——这叫"按低 8 位截断"。 */
    for(i=32;i<=107;i++){  // for循环：从i=32开始，到i=107结束，每次i增加1
        printf("%c ",i);   // 将整数i作为ASCII码，输出对应的字符（%c=字符格式）
    }
    printf("\n");            // 输出换行符，换行
    /* ===== 字符串终止符：两种写法的本质区别 =====
     * 字符串字面量 "abc" 在编译时会被自动追加一个字节 0（写作 '\0'），
     * 它叫「英文术语: null terminator（空字符终止符）」，也叫「行业术语: sentinel（哨兵值）」，
     * 所以 arr1 实际占 4 字节：'a' 'b' 'c' '\0'。
     * arr2 用三个字符逐个初始化，编译器【不会】自动加 '\0'，只占 3 字节。
     * printf("%s") 的原理：从数组第一个字节开始逐个输出，遇到字节 0 才停。
     * arr2 没有 0，它会【越界】往后读内存，直到碰巧遇到某个 0——读多少全凭运气，
     * 这叫「英文术语: undefined behavior（未定义行为, UB）」：结果不可预料，是 C 里最常见的坑。 */
    char arr1[] = "abc";
    char arr2[] = {'a','b','c'};

    printf("%s\n", arr1);
    printf("%s\n", arr2);

    /* 「英文术语: UTF-8」编码规则：一个汉字（含全角标点"？"）占 3 个字节，
     * 一个 ASCII 字符（英文字母/数字/半角符号）占 1 字节。
     * 下面字符串里的全角"？"每个都是 3 字节，前面英文和空格各 1 字节。 */
    printf("are  u ok ?？？\n");
    printf("C\\Users\\username\\Documents\n");   // 每个 \\ 编译期固化成一个反斜杠字节 0x5C，屏幕上显示的反斜杠数量是源码里的一半
    printf("He said:\"Hi\\tthere!\"\n");        // \" 编译期变成双引号字节 0x22；\\t 是 \ 和 t 两个普通字符，不是制表符
    /* strlen 的原理：从数组第一个字节开始往后逐个数，遇到字节 0 就停下，返回数过的个数。
     * arr2 没有 '\0'，strlen 会越界继续数——这里能算出 3 纯属运气好（紧邻内存恰好是 0），
     * 本质仍是未定义行为(UB)；正确写法：char arr2[] = {'a','b','c','\0'}; */
    int len =strlen(arr2);
    printf("len = %d\n",len);
    int b = 100;                 // int 占 4 字节，100 以二进制形式存在栈上
    int adg = 200;
    printf("adg - b = %d\n",adg-b);  // 先算出表达式 adg-b 的值(100)，再把这个值替换进 %d

    return 0;              // 返回0，表示程序正常结束
}