/* ===== #include 的底层原理 =====
 * 编译一个 .c 文件分四步：预处理(preprocess) → 编译(compile) → 汇编(assemble) → 链接(link)。
 * #include 发生在第一步"预处理"：把头文件内容原样"粘贴"到这里。
 * stdio.h 提供 printf 的声明，stdlib.h 提供 system 的声明；
 * 函数真正的机器码在链接阶段从 C 标准库（英文术语: libc）合并进来。 */
#include <stdio.h>
#include <stdlib.h>

int main() {
    /* system() 让操作系统执行一条命令；chcp 65001 把控制台「英文术语: codepage（代码页）」
     * 切成 65001 号（即 UTF-8 编码）。不切换的话，下面的 UTF-8 中文会按 GBK 解码 → 乱码。 */
    system("chcp 65001");  // 设置UTF-8

    /* ===== 转义字符与字符串常量的底层原理 =====
     * 转义序列在【编译期】就被固化成真实字节：\n→0x0A，\t→0x09，\\→0x5C，\"→0x22，\'→0x27。
     * 运行时 printf 拿到的只是普通字节，不再做任何"翻译"。
     * 双引号括起来的字符串常量存放在「英文术语: .rodata（只读数据段）」，只读不可改。
     * 每一行 printf(...) 都是一次「英文术语: function call statement（函数调用语句）」：
     * 跳转到 printf 的代码，把字符串里的字节依次送到控制台，再返回继续往下走。
     * 「英文术语: UTF-8」编码：一个汉字占 3 字节，一个 ASCII 字符（字母/数字/标点）占 1 字节。 */
    printf("第一行\n第二行\n");      // \n 换行：编译期已变成字节 0x0A，控制台收到它就光标移到下一行
    printf("姓名\t年龄\t城市\n");     // \t 制表符对齐：\t 本身只占 1 字节(0x09)，是【控制台】把它按"制表位"展开成若干空格来显示，不是 printf 输出了空格
    printf("张三\t20\t北京\n");       // 每个汉字 3 字节(UTF-8)，"20" 两个 ASCII 字符各 1 字节
    printf("李四\t25\t上海\n");

    printf("路径：C:\\Users\\test\n");  // \\ 打印一个反斜杠：编译期两个字符 \\ 固化成一个字节 0x5C
    printf("他说：\"你好\"\n");         // \" 打印双引符：编译期变成字节 0x22，防止被当成字符串结束符
    printf("字符：\'A\'\n");           // \' 打印单引号：变成字节 0x27（双引号字符串里直接写 ' 也可以）

    return 0;  // 把 0 返回给操作系统，表示"正常结束"；非 0 一般代表出错
}